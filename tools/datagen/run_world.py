#!/usr/bin/env python3
"""Generate reviewed map-zone and unscaled boss metadata from this checkout."""

import argparse
import hashlib
import json
import re
from pathlib import Path


def read_maps(root):
    text = (root / "include/data/map_headers.h").read_text(encoding="utf-8")
    return [(name, re.search(r"\.mapLabelTextID\s*=\s*(\w+)", body).group(1))
            for name, body in re.findall(r"\[(MAP_HEADER_\w+)\]\s*=\s*\{(.*?)\n    \}", text, re.S)]


def generate(root):
    names = (root / "generated/map_headers.txt").read_text().splitlines()
    names = names[:names.index("MAP_HEADER_COUNT")]
    labels = json.loads((root / "res/text/location_names.json").read_text(encoding="utf-8"))["messages"]
    label_ids = {message["id"]: i for i, message in enumerate(labels)}
    manifest = json.loads((root / "tools/datagen/run_zones.json").read_text(encoding="utf-8"))
    zones = {}
    for group in manifest["groups"]:
        zone = label_ids[group["location"]]
        if zone >= 256:
            raise ValueError("Zone IDs must fit in the persistent 256-zone table")
        for name in group["maps"]:
            if name in zones:
                raise ValueError(f"Map assigned twice: {name}")
            zones[name] = zone
    if set(zones) != set(names):
        raise ValueError(f"Map-zone manifest requires review: {set(zones) ^ set(names)}")
    caps = []
    for boss in ("leader_roark", "leader_gardenia", "leader_fantina", "leader_maylene",
                 "leader_wake", "leader_byron", "leader_candice", "leader_volkner", "champion_cynthia"):
        trainer = json.loads((root / "res/trainers/data" / (boss + ".json")).read_text(encoding="utf-8"))
        caps.append(max(mon["level"] for mon in trainer["party"]))
    trainers = (root / "generated/trainers.txt").read_text().splitlines()
    trainers = trainers[:trainers.index("MAX_TRAINERS")]
    bosses = []
    for name in trainers:
        path = root / "res/trainers/data" / (name.removeprefix("TRAINER_").lower() + ".json")
        if path.exists():
            category = json.loads(path.read_text(encoding="utf-8"))["class"]
            bosses.append(int(any(term in category for term in ("LEADER_", "COMMANDER", "GALACTIC_BOSS", "CHAMPION", "ELITE_FOUR", "RIVAL"))))
        else:
            bosses.append(0)
    version = int.from_bytes(hashlib.sha256(json.dumps([zones, caps, bosses], sort_keys=True).encode()).digest()[:4], "little")
    # UI metadata only: keep the published gameplay grouping fingerprint stable.
    map_text = (root / "include/data/map_headers.h").read_text(encoding="utf-8")
    wild_zones = set()
    for name, body in re.findall(r"\[(MAP_HEADER_\w+)\]\s*=\s*\{(.*?)\n    \}", map_text, re.S):
        encounter = re.search(r"\.wildEncountersArchiveID\s*=\s*(\w+)", body)
        if encounter and encounter.group(1) != "ENCOUNTERS_NONE":
            wild_zones.add(zones[name])
    lines = ["// Generated by tools/datagen/run_world.py; do not edit.",
             "#ifndef POKEPLATINUM_RUN_WORLD_DATA_H", "#define POKEPLATINUM_RUN_WORLD_DATA_H",
             f"#define RUN_WORLD_DATA_VERSION 0x{version:08X}u", f"#define RUN_MAP_COUNT {len(names)}",
             f"#define RUN_TRAINER_COUNT {len(trainers)}", "#ifdef RUN_INCLUDE_WORLD_TABLES"]
    for ctype, symbol, values in (("u8", "sRunMapZones", [zones[name] for name in names]),
                                 ("u8", "sRunBaseCaps", caps), ("u8", "sRunTrainerBoss", bosses),
                                 ("u8", "sRunKnownZones", [int(zone in zones.values()) for zone in range(256)]),
                                 ("u8", "sRunWildZones", [int(zone in wild_zones) for zone in range(256)])):
        lines.append(f"static const {ctype} {symbol}[{len(values)}] = {{")
        lines.extend("    " + ", ".join(map(str, values[i:i + 16])) + "," for i in range(0, len(values), 16))
        lines.append("};")
    lines += ["#endif", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--depfile", type=Path)
    parser.add_argument("--initialize-zones", action="store_true")
    args = parser.parse_args()
    if args.initialize_zones:
        target = args.root / "tools/datagen/run_zones.json"
        if target.exists():
            raise SystemExit("Refusing to replace the reviewed map-zone manifest")
        groups = {}
        for name, label in read_maps(args.root):
            groups.setdefault(label, []).append(name)
        target.write_text(json.dumps({
            "policy": "Explicit map-header membership. Route grass/surf/fishing share one zone. All floors of each named cave, forest, lake and facility share its logical zone. Town interiors share the town's zone. Mystery/unknown maps share the non-capture Mystery Zone. New map IDs require manifest review.",
            "groups": [{"location": label, "maps": maps} for label, maps in groups.items()]
        }, indent=2) + "\n", encoding="utf-8", newline="\n")
    elif args.output:
        content = generate(args.root)
        if not args.output.exists() or args.output.read_text() != content:
            args.output.write_text(content, encoding="ascii", newline="\n")
        if args.depfile:
            def escape(path):
                return str(path).replace("\\", "/").replace("$", "$$").replace(" ", "\\ ").replace("#", "\\#")
            dependencies = sorted((args.root / "res/trainers/data").glob("*.json"))
            args.depfile.write_text(escape(args.output) + ": " + " ".join(map(escape, dependencies)) + "\n", encoding="utf-8")
    else:
        parser.error("--output or --initialize-zones is required")


if __name__ == "__main__":
    main()
