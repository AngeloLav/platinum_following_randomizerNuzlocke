#!/usr/bin/env python3
"""Generate compact randomizer data from this checkout, without third-party modules."""

import argparse
import hashlib
import json
from pathlib import Path


def generate(root):
    names = (root / "generated/species.txt").read_text(encoding="utf-8").splitlines()
    end = names.index("SPECIES_EGG")
    names = names[:end]
    if names[0] != "SPECIES_NONE" or end != 494:
        raise ValueError("Unexpected species roster; review the randomizer data version")
    ids = {name: i for i, name in enumerate(names)}
    parents = list(range(end))

    def find(species):
        while parents[species] != species:
            parents[species] = parents[parents[species]]
            species = parents[species]
        return species

    def join(a, b):
        a, b = find(a), find(b)
        parents[max(a, b)] = min(a, b)

    totals = [0] * end
    classes = [0] * end
    stat_names = {"hp", "attack", "defense", "speed", "special_attack", "special_defense"}
    for species, name in enumerate(names[1:], start=1):
        path = root / "res/pokemon" / name.removeprefix("SPECIES_").lower() / "data.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        stats = data["base_stats"]
        if set(stats) != stat_names or any(type(value) is not int or not 1 <= value <= 255 for value in stats.values()):
            raise ValueError(f"Invalid base stats: {path}")
        totals[species] = sum(stats.values())
        for evolution in data.get("evolutions", []):
            target = evolution[-1]
            if target not in ids or ids[target] == 0:
                raise ValueError(f"Invalid evolution target: {path}: {target}")
            join(species, ids[target])

    # Breeding siblings are one ownership family even without a direct evolution edge.
    join(ids["SPECIES_NIDORAN_F"], ids["SPECIES_NIDORAN_M"])
    join(ids["SPECIES_VOLBEAT"], ids["SPECIES_ILLUMISE"])
    join(ids["SPECIES_PHIONE"], ids["SPECIES_MANAPHY"])
    families = [find(species) for species in range(end)]

    classifications = json.loads((root / "tools/datagen/run_species_classes.json").read_text(encoding="utf-8"))
    if set(classifications) != {"legendary", "mythical"}:
        raise ValueError("Unknown classification")
    seen = set()
    for category, value in (("legendary", 1), ("mythical", 2)):
        for name in classifications[category]:
            symbol = "SPECIES_" + name
            if symbol not in ids or symbol in seen or ids[symbol] == 0:
                raise ValueError(f"Invalid or repeated classified species: {symbol}")
            seen.add(symbol)
            classes[ids[symbol]] = value

    # Includes IDs: changing order cannot accidentally retain a data fingerprint.
    canonical = json.dumps([names, totals, families, classes], separators=(",", ":")).encode("ascii")
    fingerprint = int.from_bytes(hashlib.sha256(canonical).digest()[:4], "little")
    lines = [
        "// Generated by tools/datagen/run_species.py. Do not edit.",
        "#ifndef POKEPLATINUM_RUN_SPECIES_DATA_H",
        "#define POKEPLATINUM_RUN_SPECIES_DATA_H",
        "",
        f"#define RUN_SPECIES_COUNT {end - 1}",
        f"#define RUN_SPECIES_DATA_VERSION 0x{fingerprint:08X}u",
    ]
    for name, c_type, values in (("BST", "u16", totals), ("Family", "u16", families), ("Class", "u8", classes)):
        # The config translation unit only needs the fingerprint, not another ROM table.
        lines += ["", "#ifdef RUN_INCLUDE_SPECIES_TABLES", f"static const {c_type} sRunSpecies{name}[{end}] = {{"]
        lines.extend("    " + ", ".join(map(str, values[i:i + 16])) + "," for i in range(0, end, 16))
        lines += ["};", "#endif"]
    lines += ["", "#endif // POKEPLATINUM_RUN_SPECIES_DATA_H", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    content = generate(args.root)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
        args.output.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
